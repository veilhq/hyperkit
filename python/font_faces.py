"""
Font-face helper - Hyperkit shared Python module.

Emits the ecosystem's @font-face rules with the font files embedded as base64
data URIs. Every app inlines its CSS (pywebview html=, single-file exports), so
a relative font URL would not resolve; data URIs work in every delivery path
and keep the apps rendering identically offline.

Sources (both SIL OFL, licenses alongside in ../fonts/):
- Departure Mono v1.500, official release (github.com/rektdeckard/departure-mono)
- Host Grotesk variable, latin + latin-ext subsets from Google Fonts
"""
from __future__ import annotations

import base64
from functools import lru_cache
from pathlib import Path

FONTS_DIR = Path(__file__).resolve().parent.parent / "fonts"

# Unicode ranges copied from the Google Fonts subsets so the browser only
# decodes the latin-ext file when such characters appear.
_LATIN = (
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, "
    "U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, "
    "U+2212, U+2215, U+FEFF, U+FFFD"
)
_LATIN_EXT = (
    "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, "
    "U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, "
    "U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF"
)

# (family, file, style, weight, unicode-range or None)
FONT_FACES = (
    ("Departure Mono", "DepartureMono-Regular.woff2", "normal", "400", None),
    ("Host Grotesk", "HostGrotesk-latin.woff2", "normal", "300 800", _LATIN),
    ("Host Grotesk", "HostGrotesk-latin-ext.woff2", "normal", "300 800", _LATIN_EXT),
    ("Host Grotesk", "HostGrotesk-Italic-latin.woff2", "italic", "300 800", _LATIN),
    ("Host Grotesk", "HostGrotesk-Italic-latin-ext.woff2", "italic", "300 800", _LATIN_EXT),
)


def _data_uri(filename: str) -> str:
    path = FONTS_DIR / filename
    if not path.exists():
        raise FileNotFoundError(
            f"Hyperkit font file missing: {path}\n"
            "Restore .hyperspace/.hyperkit/fonts/ - every app build embeds these files."
        )
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:font/woff2;base64,{encoded}"


@lru_cache(maxsize=1)
def font_face_css() -> str:
    """Return the @font-face block for all ecosystem faces, ready to prepend to app CSS."""
    rules = ["/* ===== Hyperkit - self-hosted font faces (generated by font_faces.py) ===== */"]
    for family, filename, style, weight, unicode_range in FONT_FACES:
        lines = [
            "@font-face {",
            f"  font-family: '{family}';",
            f"  src: url({_data_uri(filename)}) format('woff2');",
            f"  font-style: {style};",
            f"  font-weight: {weight};",
            "  font-display: swap;",
        ]
        if unicode_range:
            lines.append(f"  unicode-range: {unicode_range};")
        lines.append("}")
        rules.append("\n".join(lines))
    return "\n".join(rules) + "\n"
